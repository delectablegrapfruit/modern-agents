  // ---- cache and public API -------------------------------------------------------------------------
  var cache = new Map();
  var urlCache = new Map();

  function makeCanvas(px) {
    if (typeof document !== 'undefined') { var c = document.createElement('canvas'); c.width = px; c.height = px; return c; }
    if (typeof OffscreenCanvas === 'function') return new OffscreenCanvas(px, px);
    return null;
  }

  function drawer(name) {
    var d = SR.reg.icon[name];
    if (typeof d === 'function') return d;
    if (d && typeof d.draw === 'function') return function (ctx, size, state) { d.draw(ctx, size, state); };
    SR.util.warnOnce('icon:' + name, 'SR.art.icon: unknown icon "' + name + '"');
    return missing;
  }
  function missing(ctx, size) {
    var k = size / 48;
    ctx.save(); ctx.scale(k, k);
    ctx.setLineDash([4, 3]); ctx.lineWidth = 2; ctx.strokeStyle = SR.art.draw.color('ui.ink-300');
    ctx.strokeRect(6, 6, 36, 36); ctx.setLineDash([]);
    ctx.fillStyle = SR.art.draw.color('ui.ink-500'); ctx.font = SR.art.draw.font(22, 900, 'display');
    ctx.textAlign = 'center'; ctx.textBaseline = 'middle'; ctx.fillText('?', 24, 25);
    ctx.restore();
  }

  function sprite(name, size, scale, state) {
    var key = name + '|' + size + '|' + scale + '|' + (state || '');
    var hit = cache.get(key);
    if (hit) return hit;
    var px = Math.max(1, Math.ceil(size * scale));
    var c = makeCanvas(px);
    if (!c) return null;
    var g = c.getContext('2d');
    g.scale(px / size, px / size);
    drawer(name)(g, size, state);
    cache.set(key, c);
    return c;
  }

  /**
   * Draws an icon from the cache with its top-left corner at (x, y), size × size in ctx units.
   * @param {CanvasRenderingContext2D} ctx
   * @param {string} name
   * @param {number} x
   * @param {number} y
   * @param {number} size
   * @param {string=} state 'disabled'
   */
  function icon(ctx, name, x, y, size, state) {
    var t = ctx.getTransform ? ctx.getTransform() : null;
    var sc = t ? Math.sqrt(t.a * t.a + t.b * t.b) : 1;
    sc = Math.max(0.25, Math.ceil(sc * 4) / 4); // quantised device scale keeps the cache small
    var s = sprite(name, size, sc, state);
    if (s) ctx.drawImage(s, x, y, size, size);
  }

  /**
   * A PNG data URL of an icon for the DOM, rendered at ≥ 2× (and at the stage's device scale).
   * @param {string} name
   * @param {number} size CSS px
   * @param {string=} state 'disabled'
   * @returns {string}
   */
  function iconURL(name, size, state) {
    size = size || 24;
    var dpr = (typeof window !== 'undefined' && window.devicePixelRatio) || 1;
    var uiK = SR.stage && SR.stage.uiK ? SR.stage.uiK : 1;
    var scale = Math.max(2, Math.ceil(dpr * uiK));
    var key = name + '|' + size + '|' + scale + '|' + (state || '');
    var hit = urlCache.get(key);
    if (hit) return hit;
    var c = sprite(name, size, scale, state);
    var url = c && c.toDataURL ? c.toDataURL('image/png') : '';
    urlCache.set(key, url);
    return url;
  }

