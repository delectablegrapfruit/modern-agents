  // ---- rendering -------------------------------------------------------------------------------------
  function fillOf(code, pal) {
    if (!code || code === 'n') return null;
    switch (code) {
      case 'b': return pal.b;
      case 'd': return pal.d;
      case 'h': return pal.h;
      case 'l': return pal.l;
      case 'w': return pal.w;
      case 'k': return pal.k;
      case 'g': return pal.g;
      default: return pal.key(code);
    }
  }

  function paint(ctx, fill, outline, pal) {
    if (fill) { ctx.fillStyle = fill; ctx.fill(); }
    if (outline) { ctx.lineWidth = 2; ctx.strokeStyle = pal.k; ctx.stroke(); }
  }

  function run(ctx, ops, pal) {
    var D = SR.art.draw;
    for (var i = 0; i < ops.length; i++) {
      var op = ops[i];
      var kind = op[0];
      if (kind === 'l' || kind === 'a') {
        ctx.beginPath();
        if (kind === 'l') { var q = op[1]; ctx.moveTo(q[0], q[1]); for (var j = 2; j < q.length; j += 2) ctx.lineTo(q[j], q[j + 1]); }
        else ctx.arc(op[1], op[2], op[3], op[4] * Math.PI / 180, op[5] * Math.PI / 180);
        var w = kind === 'l' ? op[2] : op[6];
        var ck = kind === 'l' ? op[3] : op[7];
        ctx.lineWidth = w || 2;
        ctx.strokeStyle = ck ? (fillOf(ck, pal) || pal.k) : pal.k;
        ctx.stroke();
        continue;
      }
      var fc = kind === 'c' ? op[4] : kind === 'e' ? op[5] : kind === 'r' ? op[5] : kind === 'p' || kind === 's' ? op[2] : op[5];
      var outline = true;
      if (typeof fc === 'string' && fc.charAt(fc.length - 1) === '!') { outline = false; fc = fc.slice(0, -1); }
      var fill = fillOf(fc, pal);
      if (fc === 'n') outline = true;
      switch (kind) {
        case 'c': ctx.beginPath(); ctx.arc(op[1], op[2], op[3], 0, Math.PI * 2); paint(ctx, fill, outline, pal); break;
        case 'e': ctx.beginPath(); ctx.ellipse(op[1], op[2], op[3], op[4], (op[6] || 0) * Math.PI / 180, 0, Math.PI * 2); paint(ctx, fill, outline, pal); break;
        case 'r':
          if (op[7]) {
            ctx.save(); ctx.translate(op[1] + op[3] / 2, op[2] + op[4] / 2); ctx.rotate(op[7] * Math.PI / 180);
            D.roundRect(ctx, -op[3] / 2, -op[4] / 2, op[3], op[4], op[6] || 0); paint(ctx, fill, outline, pal); ctx.restore();
          } else { D.roundRect(ctx, op[1], op[2], op[3], op[4], op[6] || 0); paint(ctx, fill, outline, pal); }
          break;
        case 'p': D.poly(ctx, op[1]); paint(ctx, fill, outline, pal); break;
        case 's':
          if (typeof Path2D === 'function') {
            var p2 = pathCache[op[1]] || (pathCache[op[1]] = new Path2D(op[1]));
            if (fill) { ctx.fillStyle = fill; ctx.fill(p2); }
            if (outline) { ctx.lineWidth = fc === 'n' ? 2.5 : 2; ctx.strokeStyle = pal.k; ctx.stroke(p2); }
          }
          break;
        case 't':
          ctx.font = D.font(op[4], 900, 'display');
          ctx.textAlign = 'center'; ctx.textBaseline = 'middle';
          if (outline) { ctx.lineWidth = 2; ctx.strokeStyle = pal.k; ctx.lineJoin = 'round'; ctx.strokeText(op[1], op[2], op[3]); }
          ctx.fillStyle = fill || pal.k; ctx.fillText(op[1], op[2], op[3]);
          break;
        default: break;
      }
    }
  }
  var pathCache = {};

  function palFor(base, state) {
    var D = SR.art.draw;
    var b = state === 'disabled' ? D.color('ui.ink-300') : D.color(base);
    var disabled = state === 'disabled';
    return {
      b: b, d: D.tone(b, -1), h: D.tone(b, 1), l: D.color('ui.paper-0'), w: D.color('white'), k: D.color(disabled ? 'ui.ink-500' : 'ui.ink-900'),
      g: disabled ? D.color('ui.ink-300') : D.color('fx.coin'),
      key: function (k) { return disabled && k !== 'ui.paper-0' && k !== 'white' && k !== 'w' ? D.mix(D.color(k), D.color('ui.ink-300'), 0.7) : D.color(k); },
    };
  }

  function makeDraw(name, entry) {
    var fn = function (ctx, size, state) {
      var k = (size || 48) / 48;
      ctx.save();
      ctx.scale(k, k);
      ctx.lineJoin = 'round';
      ctx.lineCap = 'round';
      run(ctx, entry[1], palFor(entry[0], state));
      ctx.restore();
    };
    fn.base = entry[0];
    return fn;
  }

