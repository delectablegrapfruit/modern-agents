// Writes js/defaults-data.js: the built-in player pictures as data URLs. The game reads the player's pixels to build
// its hitbox, and a page opened straight from a file may not read pixels of files next to it, but it may read these.
//   node scripts/embed-defaults.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const FILES = { 'player-sticker.svg': 'image/svg+xml', 'player-pixel.gif': 'image/gif' };
const lines = Object.entries(FILES).map(([name, type]) => {
  const b64 = readFileSync(resolve(HERE, '../assets/defaults', name)).toString('base64');
  return `  '${name}': 'data:${type};base64,${b64}',`;
});
const out = `/* Generated by scripts/embed-defaults.mjs from assets/defaults/ - do not edit. The built-in player pictures as data
 * URLs, so their pixels (the hitbox) can be read even when the game is opened straight from a file. */
window.MZ = window.MZ || {};
window.MZ.DEFAULT_DATA = {
${lines.join('\n')}
};
`;
writeFileSync(resolve(HERE, '../js/defaults-data.js'), out);
console.log('wrote js/defaults-data.js (' + out.length + ' bytes)');
